import assert from 'node:assert/strict'
const a=await import(process.env.ARENA_TEST_MODULE)
const team=['classico-naruto','classico-young-kakashi','classico-sakura'].map(id=>a.characters.find(c=>c.id===id))
const state=a.createBattle(team,team,'player-1',100,1000)
const session=a.createLocalSession(state,1000)
const p1=a.publicSessionFor(session,'player-1',false),p2=a.publicSessionFor(session,'player-2',false)
const first=a.renderRemoteBattle(p1,'player-1'),second=a.renderRemoteBattle(p2,'player-2')
assert(first.includes('Consultar perfil de Ana'));assert(second.includes('Consultar perfil de Bruno'))
assert(second.includes('OPPONENT TURN...'))
assert(second.indexOf('aria-label="Equipe do Jogador 2"')<second.indexOf('aria-label="Equipe do Jogador 1"'))
assert(a.renderRemoteBattle({...p2,battle:{...p2.battle,phase:'finished',winnerId:'player-2',turnEndsAt:null}},'player-2').includes('VITÓRIA'))
assert(a.renderRemoteBattle({...p1,battle:{...p1.battle,phase:'finished',winnerId:'player-2',turnEndsAt:null}},'player-1').includes('DERROTA'))
assert.match(a.multiplayerVersion,/^arena-4-[a-f\d]+$/)
assert(/<button[^>]*disabled=""[^>]*>Partida privada online<\/button>/.test(a.renderSelection([team[0],team[1],null])))
assert(/<button(?![^>]*disabled)[^>]*>Partida privada online<\/button>/.test(a.renderSelection(team)))
const hidden=state.players['player-2'].team[1]
hidden.statuses.push({instanceId:'fixture:hidden',statusId:'classico-young-kakashi-observe',sourcePlayerId:'player-2',sourceCharacterId:hidden.instanceId,sourceSkillId:'classico-young-kakashi-3',expiration:{playerId:'player-1',afterTurn:99}})
const publicState=a.publicSessionFor(a.createLocalSession(state,1000),'player-1',false)
assert.equal(publicState.battle.players['player-2'].team[1].statuses.length,0)
assert.equal(state.players['player-2'].team[1].statuses.length,1)
console.log('PASS Online perspectives, results, valid-team requirement and hidden effects stay private with retained characters.')
