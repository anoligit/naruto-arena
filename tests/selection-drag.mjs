import assert from 'node:assert/strict'
const a=await import(process.env.ARENA_TEST_MODULE)
const find=id=>a.characters.find(c=>c.id===`classico-${id}`)
const [naruto,sasuke,sakura,haku]=['naruto','sasuke','sakura','haku'].map(find)
const source=(character,fromSlot=null)=>({character,fromSlot})
const slot=index=>({type:'team',slot:index})
const catalog={type:'catalog'}
let team=[null,null,null]
let next=a.applyCharacterDrop(team,source(naruto),slot(1),true)
assert.deepEqual(team,[null,null,null]);assert.deepEqual(next,[null,naruto,null])
assert(a.canDropCharacter(team,source(naruto),slot(1),true))
team=next
assert.equal(a.applyCharacterDrop(team,source(sasuke),slot(1),true),team)
assert.equal(a.applyCharacterDrop(team,source(naruto),slot(0),true),team)
assert.equal(a.applyCharacterDrop(team,source(haku),slot(0),false),team)
assert.equal(a.applyCharacterDrop(team,source(naruto),catalog,true),team)
assert.equal(a.applyCharacterDrop(team,source(naruto),slot(-1),true),team)
assert.equal(a.applyCharacterDrop(team,source(naruto),slot(99),true),team)
assert.equal(a.applyCharacterDrop(team,source(naruto),slot(0.5),true),team)
team=[naruto,sasuke,sakura]
next=a.applyCharacterDrop(team,source(naruto,0),slot(2),true)
assert.deepEqual(next,[sakura,sasuke,naruto]);assert.deepEqual(team,[naruto,sasuke,sakura])
assert.equal(new Set(next.map(c=>c.id)).size,3)
assert.equal(a.applyCharacterDrop(team,source(naruto,0),slot(0),true),team)
assert(a.canDropCharacter(team,source(naruto,0),slot(0),true))
next=a.applyCharacterDrop(team,source(sasuke,1),catalog,true)
assert.deepEqual(next,[naruto,null,sakura]);assert.deepEqual(team,[naruto,sasuke,sakura])
assert.deepEqual(a.applyCharacterDrop([haku,null,null],source(haku,0),catalog,false),[null,null,null])
assert.equal(a.applyCharacterDrop(team,source(naruto,1),catalog,true),team,'Stale source must not remove another character')
assert.equal(a.applyCharacterDrop(team,source(naruto,1),slot(2),true),team)
assert.equal(a.applyCharacterDrop(team,source(naruto,0),slot(2),false),team)
const orderBefore=a.characters.map(c=>c.id)
const html=a.renderSelection([naruto,null,null])
assert(html.includes('data-character-catalog'))
assert.equal((html.match(/data-team-slot=/g)??[]).length,3)
assert(!html.includes('draggable="true"'),'Native browser drag must not produce a second ghost image')
assert(html.includes('class="character in-team'))
assert.deepEqual(a.characters.map(c=>c.id),orderBefore)
console.log('PASS Selection drag: placement, move/swap, catalog return, occupied/duplicate/locked/invalid targets, stale teams, input immutability, native-drag suppression and unchanged catalog order.')
