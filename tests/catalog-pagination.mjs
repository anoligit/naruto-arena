import assert from 'node:assert/strict'
const a=await import(process.env.ARENA_TEST_MODULE)
const ids=characters=>characters.map(c=>c.id)
const before=ids(a.characters)
const first=a.getCatalogPage(a.characters,0,false),second=a.getCatalogPage(a.characters,1,false)
assert.equal(first.pageSize,21);assert.equal(first.characters.length,21);assert.equal(first.pageCount,2)
assert.deepEqual(ids(first.characters),before.slice(0,21))
assert.deepEqual(ids(second.characters),['classico-haku'])
assert.deepEqual([...ids(first.characters),...ids(second.characters)],before)
assert.deepEqual(ids(a.getCatalogPage(a.characters,999,false).characters),ids(second.characters))
assert.equal(a.getCatalogPage(a.characters,-1,false).page,0)
assert.equal(a.getCatalogPage(a.characters,NaN,false).page,0)
assert.equal(a.getCatalogPage([],0,false).pageCount,1)
assert.deepEqual(a.getCatalogPage([],0,false).characters,[])
for(const n of [21,42,43]){
 const roster=Array.from({length:n},(_,i)=>({...a.characters[0],id:`fixture-${i}`}))
 const pages=Array.from({length:Math.ceil(n/21)},(_,page)=>a.getCatalogPage(roster,page,false).characters)
 assert(pages.every(page=>page.length<=21))
 assert.deepEqual(pages.flat().map(c=>c.id),roster.map(c=>c.id))
}
const mobileFirst=a.getCatalogPage(a.characters,0,true),mobileSecond=a.getCatalogPage(a.characters,1,true)
assert.equal(mobileFirst.characters.length,20);assert.equal(mobileSecond.characters.length,2)
assert.deepEqual([...ids(mobileFirst.characters),...ids(mobileSecond.characters)],before)
const markup=a.renderSelection([null,null,null])
assert.equal((markup.match(/data-character-id=/g)??[]).length,21)
assert(markup.includes('desktop-catalog-pagination'))
assert(markup.includes('Página 1 de 2'))
assert(markup.includes('selection-desktop-account'))
assert(!markup.includes('data-character-id="classico-haku"'))
assert.deepEqual(ids(a.characters),before)
console.log('PASS Desktop pages hold 21 characters with Haku on page two; page bounds, exact multiples, empty catalog, stable order, desktop profile/team regions and unchanged 20-character mobile pages.')
