import assert from 'node:assert/strict'
const a=await import(process.env.ARENA_TEST_MODULE)
const roster=['classico-naruto','classico-sasuke','classico-sakura'].map(id=>a.characters.find(c=>c.id===id))
const setup=()=>a.createBattle(roster,roster,'player-1',100,1000)
const remote=(s,viewer)=>a.renderRemoteBattle(a.publicSessionFor(a.createLocalSession(s,1000),viewer,false),viewer)
const battle=setup(),before=structuredClone(battle)
const own=remote(battle,'player-1'),other=remote(battle,'player-2')
assert.equal((own.match(/class="battle-skills"/g)??[]).length,3)
assert(other.includes('OPPONENT TURN...'))
assert.equal((other.match(/class="assigned-skill /g)??[]).length,0)
const profiles={'player-1':a.createBattleProfile('Ana'),'player-2':a.createBattleProfile('Bruno')}
const profile=a.renderBattleInspection(battle,{playerId:'player-2'},profiles)
assert(profile.includes('Perfil de Bruno'))
for(const c of roster)assert(profile.includes(`alt="${c.name}"`))
const inspected=a.renderBattleInspection(battle,{characterInstanceId:'player-1:classico-naruto',skillName:'Rasengan'},profiles)
assert(inspected.includes('inspection-energy'));assert(inspected.includes('Recarga'));assert(inspected.includes('Classes'))
assert(inspected.indexOf('inspection-energy')<inspected.indexOf('inspection-description'))
assert.equal((inspected.match(/class="inspection-skill"/g)??[]).length,roster[0].skillDefinitions.length)
assert(!inspected.includes('data-use-available'))
assert.deepEqual(battle,before)
for(const [health,color] of [[1,'#ff2020'],[26,'#ff9500'],[51,'#ffe000'],[76,'#20d532']])assert(a.renderHealthBar(health,100).includes(`background:${color}`))
assert(a.renderHealthBar(100,100,70).includes('left:70%;width:30%;background:#bbf7d0'))
for(const mobile of [false,true]){
 const html=a.renderTurnControls(false,30,mobile)
 assert.equal((html.match(/role="timer"/g)??[]).length,1)
 const opponent=a.renderTurnControls(true,8,mobile)
 assert(opponent.includes('class="turn-energy-controls" hidden=""'))
}
const mobile=a.renderMobileConfirmation(setup())
assert.equal((mobile.match(/role="timer"/g)??[]).length,1)
assert(mobile.includes('Finalizar turno'))
const s=setup();s.players['player-1'].energy={taijutsu:1,bloodline:0,ninjutsu:0,genjutsu:0}
const queue=[{playerId:'player-1',characterInstanceId:'player-1:classico-naruto',skillId:'classico-naruto-1',targetInstanceId:'player-2:classico-sasuke'}]
const snapshot=structuredClone(s),empty={taijutsu:0,bloodline:0,ninjutsu:0,genjutsu:0}
const unpaid=a.renderTurnConfirmation(s,queue,empty)
assert(unpaid.includes('Consumir energia 0/1'))
assert(/disabled=""[^>]*>Confirmar turno/.test(unpaid))
const paid=a.renderTurnConfirmation(s,queue,{...empty,taijutsu:1})
assert(paid.includes('Consumir energia 1/1'));assert(!/disabled=""[^>]*>Confirmar turno/.test(paid))
assert.deepEqual(s,snapshot)
const dead=setup();dead.players['player-2'].team[0].health=0
assert(remote(dead,'player-1').includes('portrait-defeated'))
const controls=own.slice(own.indexOf('class="battle-action-buttons"'))
assert(controls.indexOf('audio-control')<controls.indexOf('surrender-control'))
assert(controls.indexOf('surrender-control')<controls.indexOf('missions-control'))
assert(controls.indexOf('missions-control')<controls.indexOf('chat-control'))
console.log('PASS Battle perspectives, profiles, skill consultation, HP colors, dead portraits, desktop/mobile timer, payment confirmation, action controls and immutable rendering with the retained roster.')
